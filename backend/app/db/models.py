"""The nine ORM tables, exactly per docs/database.md §1–§2 (approved design).

Pure schema: no business logic here. Logic lives in `app/services/`.

Conventions (docs/database.md):
- Every table has an `id` integer primary key.
- All money is integer cents (D3/D26). No floats anywhere.
- All timestamps are aware-UTC datetimes generated by the app (D33).
- Historical rows (`order_items`, `payment_ledger`) are insert-only; the
  application never exposes an update path for them (D3).
"""
from datetime import datetime
from typing import Optional

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from ..core import constants as C
from .base import Base
from .types import UTCDateTime
from .engine import utcnow


class User(Base):
    """All accounts, one table; role + ownership checked per request (D8)."""

    __tablename__ = "users"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    email: Mapped[str] = mapped_column(String(255), nullable=False)
    password_hash: Mapped[str] = mapped_column(String(128), nullable=False)
    full_name: Mapped[str] = mapped_column(String(120), nullable=False)
    role: Mapped[str] = mapped_column(String(20), nullable=False, default=C.ROLE_CUSTOMER)
    is_active: Mapped[bool] = mapped_column(Boolean, nullable=False, default=True)
    created_at: Mapped[datetime] = mapped_column(UTCDateTime, nullable=False, default=utcnow)
    updated_at: Mapped[datetime] = mapped_column(UTCDateTime, nullable=False, default=utcnow)

    __table_args__ = (
        # The UNIQUE on email doubles as the login index.
        UniqueConstraint("email", name="uq_users_email"),
        CheckConstraint(
            f"role IN ('{C.ROLE_CUSTOMER}', '{C.ROLE_OWNER}', '{C.ROLE_PARTNER}')",
            name="ck_users_role",
        ),
        # Serves the owner's active-partner listing (D5).
        Index("ix_users_role_active", "role", "is_active"),
    )

    restaurant: Mapped[Optional["Restaurant"]] = relationship(
        back_populates="owner", uselist=False, foreign_keys="Restaurant.owner_id"
    )
    orders_placed: Mapped[list["Order"]] = relationship(
        back_populates="customer", foreign_keys="Order.customer_id"
    )
    orders_delivering: Mapped[list["Order"]] = relationship(
        back_populates="delivery_partner", foreign_keys="Order.delivery_partner_id"
    )

    # Users are never hard-deleted (history anchors) — deactivated instead (D4).


class Restaurant(Base):
    """Catalog entry + ownership anchor. One owner ↔ at most one (D24)."""

    __tablename__ = "restaurants"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    owner_id: Mapped[int] = mapped_column(
        ForeignKey("users.id", ondelete="RESTRICT"), nullable=False
    )
    name: Mapped[str] = mapped_column(String(120), nullable=False)
    description: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    address: Mapped[str] = mapped_column(String(255), nullable=False)
    delivery_fee_cents: Mapped[int] = mapped_column(Integer, nullable=False, default=200)
    created_at: Mapped[datetime] = mapped_column(UTCDateTime, nullable=False, default=utcnow)
    updated_at: Mapped[datetime] = mapped_column(UTCDateTime, nullable=False, default=utcnow)

    __table_args__ = (
        # One restaurant per owner (D2/D24); also the ownership-lookup index.
        UniqueConstraint("owner_id", name="uq_restaurants_owner"),
        CheckConstraint("delivery_fee_cents >= 0", name="ck_restaurants_fee"),
    )

    owner: Mapped[User] = relationship(
        back_populates="restaurant", foreign_keys=[owner_id]
    )
    menu_items: Mapped[list["MenuItem"]] = relationship(back_populates="restaurant")
    orders: Mapped[list["Order"]] = relationship(back_populates="restaurant")


class MenuItem(Base):
    """The *current* menu truth (D3). Freely updatable; orders snapshot it."""

    __tablename__ = "menu_items"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    restaurant_id: Mapped[int] = mapped_column(
        ForeignKey("restaurants.id", ondelete="RESTRICT"), nullable=False
    )
    name: Mapped[str] = mapped_column(String(120), nullable=False)
    description: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    price_cents: Mapped[int] = mapped_column(Integer, nullable=False)
    available: Mapped[bool] = mapped_column(Boolean, nullable=False, default=True)
    created_at: Mapped[datetime] = mapped_column(UTCDateTime, nullable=False, default=utcnow)
    updated_at: Mapped[datetime] = mapped_column(UTCDateTime, nullable=False, default=utcnow)

    __table_args__ = (
        CheckConstraint("price_cents >= 0", name="ck_menu_price"),
        Index("ix_menu_rest_avail", "restaurant_id", "available"),
    )

    restaurant: Mapped[Restaurant] = relationship(back_populates="menu_items")
    # Provenance link only; historical copies live in order_items (D3/D32).


class Order(Base):
    """One checkout. Anchor for items, ledger, refund, review, reminders."""

    __tablename__ = "orders"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    customer_id: Mapped[int] = mapped_column(
        ForeignKey("users.id", ondelete="RESTRICT"), nullable=False
    )
    restaurant_id: Mapped[int] = mapped_column(
        ForeignKey("restaurants.id", ondelete="RESTRICT"), nullable=False
    )
    delivery_partner_id: Mapped[Optional[int]] = mapped_column(
        ForeignKey("users.id", ondelete="RESTRICT"), nullable=True
    )
    status: Mapped[str] = mapped_column(String(20), nullable=False, default=C.ORDER_PLACED)
    payment_status: Mapped[str] = mapped_column(
        String(20), nullable=False, default=C.PAYMENT_MOCK_PAID
    )
    status_updated_at: Mapped[datetime] = mapped_column(UTCDateTime, nullable=False, default=utcnow)
    delivered_at: Mapped[Optional[datetime]] = mapped_column(UTCDateTime, nullable=True)
    items_subtotal_cents: Mapped[int] = mapped_column(Integer, nullable=False)
    delivery_fee_cents: Mapped[int] = mapped_column(Integer, nullable=False)
    total_cents: Mapped[int] = mapped_column(Integer, nullable=False)
    delivery_address: Mapped[str] = mapped_column(String(255), nullable=False)
    idempotency_key: Mapped[str] = mapped_column(String(64), nullable=False)
    request_hash: Mapped[str] = mapped_column(String(64), nullable=False)
    created_at: Mapped[datetime] = mapped_column(UTCDateTime, nullable=False, default=utcnow)
    updated_at: Mapped[datetime] = mapped_column(UTCDateTime, nullable=False, default=utcnow)

    __table_args__ = (
        CheckConstraint(
            f"status IN ({', '.join(repr(s) for s in C.ORDER_STATUSES)})",
            name="ck_orders_status",
        ),
        CheckConstraint(
            f"payment_status IN ({', '.join(repr(s) for s in C.PAYMENT_STATUSES)})",
            name="ck_orders_payment_status",
        ),
        CheckConstraint("items_subtotal_cents >= 0", name="ck_orders_subtotal"),
        CheckConstraint("delivery_fee_cents >= 0", name="ck_orders_fee"),
        # The money identity is enforced by the DB, not just the app (CK-06).
        CheckConstraint(
            "total_cents = items_subtotal_cents + delivery_fee_cents "
            "AND total_cents >= 0",
            name="ck_orders_total_identity",
        ),
        # Duplicate-checkout backstop, scoped to the customer (D34).
        UniqueConstraint("customer_id", "idempotency_key", name="uq_orders_customer_key"),
        Index("ix_orders_customer_created", "customer_id", "created_at"),
        Index("ix_orders_customer_status", "customer_id", "status"),
        Index("ix_orders_restaurant_status", "restaurant_id", "status"),
        Index("ix_orders_restaurant_created", "restaurant_id", "created_at"),
        Index("ix_orders_status_updated", "status", "status_updated_at"),
        Index("ix_orders_partner_status", "delivery_partner_id", "status"),
    )

    customer: Mapped[User] = relationship(
        back_populates="orders_placed", foreign_keys=[customer_id]
    )
    delivery_partner: Mapped[Optional[User]] = relationship(
        back_populates="orders_delivering", foreign_keys=[delivery_partner_id]
    )
    restaurant: Mapped[Restaurant] = relationship(back_populates="orders")
    items: Mapped[list["OrderItem"]] = relationship(
        back_populates="order", cascade="all, delete-orphan"
    )
    ledger: Mapped[list["PaymentLedger"]] = relationship(
        back_populates="order", cascade="all, delete-orphan"
    )
    refund_request: Mapped[Optional["RefundRequest"]] = relationship(
        back_populates="order", uselist=False
    )
    review: Mapped[Optional["Review"]] = relationship(
        back_populates="order", uselist=False
    )
    reminders: Mapped[list["ReminderLog"]] = relationship(
        back_populates="order", cascade="all, delete-orphan"
    )


class OrderItem(Base):
    """Immutable receipt line (D3). Insert-only; no update path exists."""

    __tablename__ = "order_items"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    order_id: Mapped[int] = mapped_column(
        ForeignKey("orders.id", ondelete="RESTRICT"), nullable=False
    )
    menu_item_id: Mapped[int] = mapped_column(
        ForeignKey("menu_items.id", ondelete="RESTRICT"), nullable=False
    )
    item_name: Mapped[str] = mapped_column(String(120), nullable=False)
    unit_price_cents: Mapped[int] = mapped_column(Integer, nullable=False)
    quantity: Mapped[int] = mapped_column(Integer, nullable=False)
    line_total_cents: Mapped[int] = mapped_column(Integer, nullable=False)

    __table_args__ = (
        CheckConstraint("unit_price_cents >= 0", name="ck_order_items_price"),
        CheckConstraint("quantity > 0", name="ck_order_items_qty"),
        CheckConstraint(
            "line_total_cents = unit_price_cents * quantity "
            "AND line_total_cents >= 0",
            name="ck_order_items_line_identity",
        ),
        Index("ix_order_items_order", "order_id"),
    )

    order: Mapped[Order] = relationship(back_populates="items")
    menu_item: Mapped[MenuItem] = relationship()  # provenance only (D3/D32)


class PaymentLedger(Base):
    """Append-only money trail. Rows are never updated or deleted (D3)."""

    __tablename__ = "payment_ledger"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    order_id: Mapped[int] = mapped_column(
        ForeignKey("orders.id", ondelete="RESTRICT"), nullable=False
    )
    type: Mapped[str] = mapped_column(String(20), nullable=False)
    amount_cents: Mapped[int] = mapped_column(Integer, nullable=False)
    created_at: Mapped[datetime] = mapped_column(UTCDateTime, nullable=False, default=utcnow)

    __table_args__ = (
        CheckConstraint(
            f"type IN ('{C.PAYMENT_MOCK_PAID}', '{C.PAYMENT_REFUNDED}')",
            name="ck_ledger_type",
        ),
        CheckConstraint("amount_cents >= 0", name="ck_ledger_amount"),
        # At most one `mock_paid` and one `refunded` row per order (§6).
        UniqueConstraint("order_id", "type", name="uq_ledger_order_type"),
        Index("ix_ledger_order", "order_id"),
    )

    order: Mapped[Order] = relationship(back_populates="ledger")


class RefundRequest(Base):
    """The return/refund flow (brief §5). One per order, permanently (D28)."""

    __tablename__ = "refund_requests"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    order_id: Mapped[int] = mapped_column(
        ForeignKey("orders.id", ondelete="RESTRICT"), nullable=False
    )
    status: Mapped[str] = mapped_column(
        String(20), nullable=False, default=C.REFUND_PENDING
    )
    reason: Mapped[str] = mapped_column(Text, nullable=False)
    requested_at: Mapped[datetime] = mapped_column(UTCDateTime, nullable=False, default=utcnow)
    decided_at: Mapped[Optional[datetime]] = mapped_column(UTCDateTime, nullable=True)
    decided_by: Mapped[Optional[int]] = mapped_column(
        ForeignKey("users.id", ondelete="RESTRICT"), nullable=True
    )

    __table_args__ = (
        CheckConstraint(
            f"status IN ('{C.REFUND_PENDING}', '{C.REFUND_APPROVED}', '{C.REFUND_REJECTED}')",
            name="ck_refunds_status",
        ),
        UniqueConstraint("order_id", name="uq_refunds_order"),
        Index("ix_refunds_status", "status"),
    )

    order: Mapped[Order] = relationship(back_populates="refund_request")
    decider: Mapped[Optional[User]] = relationship()


class Review(Base):
    """One rating per (actually delivered) order (D31, REV-03)."""

    __tablename__ = "reviews"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    order_id: Mapped[int] = mapped_column(
        ForeignKey("orders.id", ondelete="RESTRICT"), nullable=False
    )
    customer_id: Mapped[int] = mapped_column(
        ForeignKey("users.id", ondelete="RESTRICT"), nullable=False
    )
    rating: Mapped[int] = mapped_column(Integer, nullable=False)
    comment: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    created_at: Mapped[datetime] = mapped_column(UTCDateTime, nullable=False, default=utcnow)

    __table_args__ = (
        CheckConstraint("rating BETWEEN 1 AND 5", name="ck_reviews_rating"),
        UniqueConstraint("order_id", name="uq_reviews_order"),
        Index("ix_reviews_customer", "customer_id"),
    )

    order: Mapped[Order] = relationship(back_populates="review")
    customer: Mapped[User] = relationship()


class ReminderLog(Base):
    """Owner reminders for stale orders (brief §8; D6, D20, D33).

    One row per (order, status-episode). No state recurs in the approved
    machine, so (order_id, status_at_reminder) fully identifies an episode.
    """

    __tablename__ = "reminder_logs"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    order_id: Mapped[int] = mapped_column(
        ForeignKey("orders.id", ondelete="RESTRICT"), nullable=False
    )
    status_at_reminder: Mapped[str] = mapped_column(String(20), nullable=False)
    detected_at: Mapped[datetime] = mapped_column(UTCDateTime, nullable=False, default=utcnow)
    resolved: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    resolved_at: Mapped[Optional[datetime]] = mapped_column(UTCDateTime, nullable=True)

    __table_args__ = (
        CheckConstraint(
            f"status_at_reminder IN ('{C.ORDER_PLACED}', '{C.ORDER_ACCEPTED}')",
            name="ck_reminders_status",
        ),
        UniqueConstraint("order_id", "status_at_reminder", name="uq_reminders_episode"),
        Index("ix_reminders_resolved", "resolved"),
        Index("ix_reminders_order", "order_id"),
    )

    order: Mapped[Order] = relationship(back_populates="reminders")
